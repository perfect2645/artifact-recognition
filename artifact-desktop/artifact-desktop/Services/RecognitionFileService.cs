using artifact.desktop.Models;
using Microsoft.Win32;
using System.Diagnostics;
using System.IO;
using System.Windows;
using System.Windows.Documents;
using System.Windows.Media.Imaging;
using Utils.Ioc;

namespace artifact.desktop.Services;

[Register(ServiceType = typeof(IRecognitionFileService), Lifetime = Lifetime.Singleton)]
public class RecognitionFileService : IRecognitionFileService
{
    public string? SelectFolder()
    {
        var dialog = new OpenFolderDialog { Title = "Select a folder containing DICOM files" };
        return dialog.ShowDialog(Application.Current.MainWindow) == true ? dialog.FolderName : null;
    }
    public Task<IReadOnlyList<RecognitionItemUi>> LoadFilesAsync(string folder, CancellationToken cancellationToken)
    {
        return Task.Run<IReadOnlyList<RecognitionItemUi>>(() =>
        {
            var options = new EnumerationOptions
            {
                RecurseSubdirectories = true,
                IgnoreInaccessible = false,
                AttributesToSkip = FileAttributes.ReparsePoint
            };
            List<RecognitionItemUi> files = [];
            foreach (var path in Directory.EnumerateFiles(folder, "*.dcm", options))
            {
                cancellationToken.ThrowIfCancellationRequested();
                // Exclude source copies generated by the worker in output/artifacts.
                var relativePath = Path.GetRelativePath(folder, path);
                if (relativePath.Split(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar)
                    .SkipLast(1).Any(part => part.Equals("output", StringComparison.OrdinalIgnoreCase)))
                    continue;
                files.Add(RecognitionItemUi.FromFile(path, folder));
            }
            return files.OrderBy(file => file.RelativePath, StringComparer.OrdinalIgnoreCase).ToArray();
        }, cancellationToken);
    }

    public Task<BitmapSource?> LoadPreviewAsync(string path, CancellationToken cancellationToken) =>
        Task.Run<BitmapSource?>(() =>
        {
            cancellationToken.ThrowIfCancellationRequested();
            var image = new BitmapImage();
            using (var stream = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.ReadWrite))
            {
                image.BeginInit();
                image.CacheOption = BitmapCacheOption.OnLoad;
                image.DecodePixelWidth = 1400;
                image.StreamSource = stream;
                image.EndInit();
                image.Freeze();
            }
            cancellationToken.ThrowIfCancellationRequested();
            return image;
        }, cancellationToken);

    public void OpenFile(string path)
    {
        if (!File.Exists(path)) throw new FileNotFoundException("The file is not available on this computer.", path);
        Process.Start(new ProcessStartInfo(path) { UseShellExecute = true });
    }
    public void ShowInFolder(string path)
    {
        if (!File.Exists(path)) throw new FileNotFoundException("The output file is not available on this computer.", path);
        var startInfo = new ProcessStartInfo("explorer.exe");
        startInfo.ArgumentList.Add($"/select,{Path.GetFullPath(path)}");
        Process.Start(startInfo);
    }

}